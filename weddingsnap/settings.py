# --- Indexing (finding faces) ------------------------------------------------------
# Photos are indexed in batches: download a few in parallel, find faces using INDEX_CPU_SLOTS cores, pause,
# then the next batch. Defaults scale with the machine, so a 1 vCPU / 512 MB droplet gets a gentle setup
# (1 photo at a time, low priority, pauses) and guests' selfie searches stay quick while indexing runs.
_cpus = os.cpu_count() or 1
try:
    _ram_gb = os.sysconf('SC_PAGE_SIZE') * os.sysconf('SC_PHYS_PAGES') / 1e9
except (ValueError, OSError, AttributeError):
    _ram_gb = 4.0
_tiny = _ram_gb < 1.5  # e.g. 512 MB / 1 GB droplets: one photo in memory at a time, one shared model copy
_small = _tiny or _cpus <= 2
INDEX_CPU_SLOTS = int(os.environ.get('INDEX_CPU_SLOTS', 1 if _small else _cpus // 2))  # photos analysed at once
INDEX_DOWNLOADS = int(os.environ.get('INDEX_DOWNLOADS', 1 if _tiny else 2 if _small else 6))  # fetched at once
INDEX_BATCH_SIZE = int(os.environ.get('INDEX_BATCH_SIZE', 10 if _small else 24))
INDEX_BATCH_PAUSE = float(os.environ.get('INDEX_BATCH_PAUSE', 1.0 if _small else 0.2))  # seconds between batches
# Linux only: indexing threads run at this lower CPU priority (0-19), so web requests always go first.
INDEX_NICE = int(os.environ.get('INDEX_NICE', 10))
# Loaded face-model copies (~60 MB each): one per indexing slot, plus one kept free for guests.
# On tiny machines indexing and guests share one copy (a guest may wait for one photo, about a second).
