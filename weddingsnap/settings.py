def r2_storage_options(endpoint, bucket, access_key, secret_key):
    from botocore.config import Config
    return {
        'bucket_name': bucket,
        'endpoint_url': endpoint,
        'access_key': access_key,
        'secret_key': secret_key,
        'region_name': 'auto',
        'signature_version': 's3v4',
        'default_acl': None,      # R2 has no ACLs; the bucket stays private
        'querystring_auth': True,  # signed, expiring download links
        'querystring_expire': 3600,
        'file_overwrite': False,
        # Only send checksums when an operation requires them, for S3-compatible services.
        'client_config': Config(request_checksum_calculation='when_required',
                                response_checksum_validation='when_required'),
    }


